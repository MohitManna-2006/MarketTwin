import { EmptyState } from "@/components/ui/States";
import type { ReplayView } from "@/lib/api/types";
import { formatElapsed, formatInteger } from "@/lib/formatting";

import { replayCode } from "./replayCodes";

type Json = Record<string, unknown>;

function flatten(
  value: unknown,
  prefix = "",
  out = new Map<string, string>(),
): Map<string, string> {
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    for (const [key, item] of Object.entries(value as Json))
      flatten(item, prefix ? `${prefix}.${key}` : key, out);
  } else {
    out.set(prefix, JSON.stringify(value));
  }
  return out;
}

function describe(record: unknown): string {
  const item = record as {
    kind?: string;
    sequence?: number;
    timestamp_ns?: number;
    correlation_id?: number | null;
  } | null;
  if (!item || typeof item !== "object") return "none";
  const parts = [item.kind ?? "record"];
  if (item.sequence !== undefined) parts.push(`sequence ${formatInteger(item.sequence)}`);
  if (item.timestamp_ns !== undefined) parts.push(formatElapsed(item.timestamp_ns, "ns"));
  if (item.correlation_id) parts.push(`order ${item.correlation_id}`);
  return parts.join(" · ");
}

function Record({
  title,
  note,
  record,
  raw,
}: {
  title: string;
  note: string;
  record: unknown;
  raw?: string | null;
}) {
  return (
    <section className="flex min-h-0 min-w-0 flex-col">
      <header className="flex h-6 shrink-0 items-center gap-2 border-b border-line-subtle bg-surface-1 px-3">
        <h3 className="label text-fg-2">{title}</h3>
        <span className="truncate text-2xs text-fg-3">{note}</span>
      </header>
      <pre
        tabIndex={0}
        className="num min-h-0 flex-1 overflow-auto px-3 py-2 text-xs leading-relaxed whitespace-pre-wrap break-all text-fg-2"
      >
        {record !== null && record !== undefined
          ? JSON.stringify(record, null, 2)
          : (raw ?? "not reported for this code")}
      </pre>
    </section>
  );
}

/**
 * The first point where the regenerated run and its recording disagree, as the engine
 * reported it: the sequence, both records, the fields that differ, and the command that
 * caused the output.
 */
export function DivergenceReport({ replay }: { replay: ReplayView }) {
  const code = replayCode(replay.code);
  if (replay.status !== "mismatch" && replay.status !== "error") {
    return (
      <EmptyState title="No divergence to report">
        {replay.status === "verified"
          ? "The regenerated run matched its recording at every record."
          : "A divergence report appears here when verification finds a difference."}
      </EmptyState>
    );
  }
  const stored = flatten(replay.expected);
  const regenerated = flatten(replay.actual);
  const fields = [...new Set([...stored.keys(), ...regenerated.keys()])].filter(
    (key) => stored.get(key) !== regenerated.get(key),
  );
  const hasRecords =
    replay.expected !== null || replay.actual !== null || replay.expected_raw || replay.actual_raw;

  return (
    <div className="flex h-full flex-col">
      <div className="grid shrink-0 grid-cols-[auto_1fr] gap-x-6 gap-y-1 border-b border-line-subtle px-3 py-2">
        <div>
          <p className="label text-fg-3">Verification error</p>
          <p className="num text-md font-medium text-neg">{replay.code}</p>
        </div>
        <div>
          <p className="label text-fg-3">
            {replay.code === "AccountingMismatch"
              ? "First mismatching accounting sequence"
              : "First mismatching sequence"}
          </p>
          <p className="num text-md font-medium text-fg">
            {replay.sequence ? formatInteger(replay.sequence) : "not at a record"}
          </p>
        </div>
        <p className="col-span-2 text-sm text-fg">{replay.message}</p>
        {code ? (
          <p className="col-span-2 max-w-[110ch] text-xs leading-snug text-fg-3">{code.meaning}</p>
        ) : null}
      </div>
      {hasRecords ? (
        <>
          {fields.length > 0 ? (
            <table className="w-full shrink-0 border-b border-line-subtle text-sm">
              <caption className="label bg-surface-1 px-3 py-1 text-left text-fg-2">
                Fields that differ · {fields.length}
              </caption>
              <thead>
                <tr className="border-y border-line-subtle">
                  <th scope="col" className="label px-3 py-1 text-left text-fg-3">
                    Field
                  </th>
                  <th scope="col" className="label px-3 py-1 text-right text-fg-3">
                    Stored in the artifact
                  </th>
                  <th scope="col" className="label px-3 py-1 text-right text-fg-3">
                    Regenerated by the engine
                  </th>
                </tr>
              </thead>
              <tbody>
                {fields.slice(0, 6).map((field) => (
                  <tr key={field} className="border-b border-line-subtle last:border-b-0">
                    <th scope="row" className="num px-3 py-1 text-left font-normal text-fg-2">
                      {field}
                    </th>
                    <td className="num px-3 py-1 text-right break-all text-fg">
                      {stored.get(field) ?? "absent"}
                    </td>
                    <td className="num px-3 py-1 text-right break-all text-fg">
                      {regenerated.get(field) ?? "absent"}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          ) : null}
          <div className="grid min-h-0 flex-1 grid-cols-2 divide-x divide-line-subtle">
            <Record
              title="Stored record"
              note="read from the run's artifact"
              record={replay.expected}
              raw={replay.expected_raw}
            />
            <Record
              title="Regenerated record"
              note="produced again from config and seed"
              record={replay.actual}
              raw={replay.actual_raw}
            />
          </div>
          <dl className="grid shrink-0 grid-cols-2 divide-x divide-line-subtle border-t border-line-subtle">
            <div className="px-3 py-1.5">
              <dt className="label text-fg-3">Causal command · last one verified</dt>
              <dd className="num truncate text-xs text-fg-2">
                {describe(replay.previous_command)}
              </dd>
            </div>
            <div className="px-3 py-1.5">
              <dt className="label text-fg-3">Last verified output</dt>
              <dd className="num truncate text-xs text-fg-2">{describe(replay.previous_output)}</dd>
            </div>
          </dl>
        </>
      ) : (
        <p className="px-3 py-2 text-sm text-fg-3">
          The engine reports no pair of records for this code: the difference is in a whole
          document, a checksum, or a missing file, as stated above.
        </p>
      )}
    </div>
  );
}
